// Builds public/search-index.json for the site search (Ctrl+K) from the pages that exist.
// Runs automatically before `next build` (see "prebuild"); run manually with:  npm run search
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PUB = "public";
const list = (dir) => (existsSync(join(PUB, dir)) ? readdirSync(join(PUB, dir)).filter((f) => f.endsWith(".html")).map((f) => (dir ? dir + "/" : "") + f) : []);
const files = [...list(""), ...list("services"), ...list("blog")];

const decode = (s) => s.replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;|&rsquo;|’/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&nbsp;/g, " ").replace(/&[a-z]+;/g, " ");
const text = (s) => decode(s.replace(/<script[\s\S]*?<\/script>/g, " ").replace(/<style[\s\S]*?<\/style>/g, " ").replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
const LEGAL = new Set(["privacy-policy", "terms-and-conditions", "cookie-policy", "accessibility", "contract-information", "disclaimer"]);

const docs = [];
for (const file of files) {
  const html = readFileSync(join(PUB, file), "utf8");
  const slug = file.replace(/\.html$/, "");
  const url = slug === "index" ? "/" : "/" + slug;
  const type = slug.startsWith("services/") ? "Service" : slug.startsWith("blog/") ? "Blog" : LEGAL.has(slug) ? "Legal" : "Page";
  const title = decode((html.match(/<title>([^<]*)<\/title>/) || [])[1] || slug).replace(/\s*\|\s*Kamboh Technologies.*$/i, "").trim();
  const desc = decode((html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || "");
  const mainStart = html.search(/<main\b/);
  const main = mainStart > -1 ? html.slice(mainStart, html.indexOf("</main>")) : html;
  // Skip decorative/duplicate parts: the mobile tab bar and footer are outside <main> already.
  const h1 = text((main.match(/<h1\b[\s\S]*?<\/h1>/) || [""])[0]);
  const heads = [...main.matchAll(/<h([23])\b([^>]*)>([\s\S]*?)<\/h\1>/g)]
    .map((m) => ({ id: (m[2].match(/\bid="([^"]+)"/) || [])[1] || "", t: text(m[3]) }))
    .filter((h) => h.t && h.t.length < 120)
    .slice(0, 24);
  const body = text(main).slice(0, 1600);
  docs.push({ u: url, t: url === "/" ? "Home" : title, y: type, d: desc, h: h1, s: heads, b: body });
}

// Most useful first when scores tie: main pages, services, blog, legal.
const ORDER = { Page: 0, Service: 1, Blog: 2, Legal: 3 };
docs.sort((a, b) => ORDER[a.y] - ORDER[b.y] || (a.u === "/" ? -1 : 0));
writeFileSync(join(PUB, "search-index.json"), JSON.stringify(docs));
console.log(`search-index.json: ${docs.length} pages, ${(JSON.stringify(docs).length / 1024).toFixed(1)}KB`);

// ---------- AI search (GEO): /llms-full.txt and the page list used by /llms.txt ----------
const SITE = "https://kambohtechnologies.com";
const toMarkdown = (html) => decode(html
  .replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<svg[\s\S]*?<\/svg>|<template[\s\S]*?<\/template>/g, " ")
  .replace(/<(ul|div|span|ol)\b[^>]*aria-hidden="true"[^>]*>[\s\S]*?<\/\1>/g, " ")
  .replace(/<h1\b[^>]*>([\s\S]*?)<\/h1>/g, "\n\n# $1\n\n")
  .replace(/<h2\b[^>]*>([\s\S]*?)<\/h2>/g, "\n\n## $1\n\n")
  .replace(/<h3\b[^>]*>([\s\S]*?)<\/h3>/g, "\n\n### $1\n\n")
  .replace(/<li\b[^>]*>/g, "\n- ")
  .replace(/<\/(p|li|ul|ol|blockquote|tr|table|section|article|div)>/g, "\n")
  .replace(/<br\s*\/?>/g, "\n")
  .replace(/<[^>]+>/g, " "))
  .replace(/[ \t]+/g, " ")
  .replace(/ *\n */g, "\n")
  .replace(/\n{3,}/g, "\n\n")
  .replace(/^(#+) +/gm, "$1 ")
  .trim();
const GROUPS = [["Page", "Main pages"], ["Service", "Services"], ["Blog", "Articles"], ["Legal", "Policies"]];
let full = `# Kamboh Technologies (Private) Limited: full website content\n\n> Software house in Johar Town, Lahore, Pakistan (SECP CUIN 0297023, FBR NTN G813109). Builds mobile apps, web applications, custom software and AI automation, and offers SECP company registration and company tax filing. This file is the text of every public page at ${SITE}, for AI assistants and search engines. A shorter summary is at ${SITE}/llms.txt.\n\nGenerated: ${new Date().toISOString().slice(0, 10)}\n`;
for (const [type, label] of GROUPS) {
  full += `\n\n=====\n# ${label}\n=====\n`;
  for (const file of files) {
    const slug = file.replace(/\.html$/, "");
    const url = slug === "index" ? "/" : "/" + slug;
    const d = docs.find((x) => x.u === url);
    if (!d || d.y !== type) continue;
    const html = readFileSync(join(PUB, file), "utf8");
    const s = html.search(/<main\b/);
    const main = s > -1 ? html.slice(s, html.indexOf("</main>")) : html;
    full += `\n\n---\n\nSource: ${SITE}${url === "/" ? "/" : url}\nTitle: ${d.t}\nSummary: ${d.d}\n\n${toMarkdown(main)}\n`;
  }
}
writeFileSync(join(PUB, "llms-full.txt"), full);
const pages = docs.map(({ u, t, y, d }) => ({ u, t, y, d }));
writeFileSync("lib/generated-site-pages.ts", `// Generated by scripts/build-search-index.mjs. Do not edit by hand.\nexport type SitePage = { u: string; t: string; y: "Page" | "Service" | "Blog" | "Legal"; d: string };\nexport const SITE_PAGES: SitePage[] = ${JSON.stringify(pages, null, 2)};\n`);
console.log(`llms-full.txt: ${(full.length / 1024).toFixed(1)}KB; lib/generated-site-pages.ts: ${pages.length} pages`);
